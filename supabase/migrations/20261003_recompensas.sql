-- ── 1. Shabat ───────────────────────────────────────────────────────────
-- Días "que cuentan" estrictamente entre dos fechas: todos menos sábados.
create or replace function public._kodesh_gap(p_from date, p_to date) returns int
language sql immutable as $$
  select coalesce((
    select count(*)::int
      from generate_series(p_from + 1, p_to - 1, interval '1 day') d
     where extract(isodow from d) <> 6
  ), 0);
$$;

create or replace function public._kodesh_settle(p_uid uuid)
returns void language plpgsql security definer set search_path = public as $$
declare
  r public.reading_streaks%rowtype;
  v_today date := public._kodesh_today(p_uid);
  v_last date;
  v_missed int;
begin
  select * into r from public.reading_streaks where user_id = p_uid for update;
  if not found or r.current_streak = 0 then return; end if;
  v_last := coalesce(r.last_active_date, r.last_read_date);
  if v_last is null then
    update public.reading_streaks set current_streak = 0 where user_id = p_uid;
    return;
  end if;
  -- Días perdidos sin contar sábados (el Shabat no rompe la racha).
  v_missed := public._kodesh_gap(v_last, v_today);
  if v_missed <= 0 then return; end if;

  if r.shields >= v_missed then
    insert into public.reading_days (user_id, day, shielded)
      select p_uid, d::date, true
        from generate_series(v_last + 1, v_today - 1, interval '1 day') d
       where extract(isodow from d) <> 6
      on conflict (user_id, day) do update set shielded = true;
    update public.reading_streaks
       set shields = shields - v_missed, last_active_date = v_today - 1, updated_at = now()
     where user_id = p_uid;
    perform public._kodesh_notice(p_uid, jsonb_build_object(
      'type', 'shield_used', 'days', v_missed, 'streak', r.current_streak, 'shields_left', r.shields - v_missed));
  else
    update public.reading_streaks set current_streak = 0, updated_at = now() where user_id = p_uid;
    perform public._kodesh_notice(p_uid, jsonb_build_object(
      'type', 'streak_lost', 'streak', r.current_streak, 'days', v_missed));
  end if;
end $$;

-- ── 2. Parashá de la semana ─────────────────────────────────────────────
-- Lectura vigente para una fecha: la próxima fecha del calendario (hoy o
-- después) si hoy cae en su semana (los 6 días anteriores + el día mismo).
create or replace function public._kodesh_parasha_for(p_today date)
returns table (reading_day date, nums int[])
language sql stable security definer set search_path = public as $$
  select c.day, c.nums
    from public.kodesh_parasha_calendar c
   where c.day >= p_today and c.day - 6 <= p_today
   order by c.day
   limit 1;
$$;

-- Progreso del usuario en la parashá vigente.
create or replace function public._kodesh_parasha_progress(p_uid uuid)
returns jsonb language plpgsql stable security definer set search_path = public as $$
declare
  v_today date := public._kodesh_today(p_uid);
  v_day date;
  v_nums int[];
  v_required text[];
  v_read text[];
  v_done boolean;
begin
  select reading_day, nums into v_day, v_nums from public._kodesh_parasha_for(v_today);
  if v_day is null then return null; end if;

  select array_agg(distinct p.book || ':' || ch)
    into v_required
    from public.kodesh_parashot p, generate_series(p.start_chapter, p.end_chapter) ch
   where p.num = any (v_nums);

  select coalesce(array_agg(distinct c), '{}')
    into v_read
    from public.reading_days d, unnest(d.chapters) c
   where d.user_id = p_uid and d.day between v_day - 6 and v_day;

  v_done := exists (select 1 from public.mana_ledger
                     where user_id = p_uid and reason = 'parasha' and detail = v_day::text);
  return jsonb_build_object(
    'reading_day', v_day,
    'nums', to_jsonb(v_nums),
    'names', (select jsonb_agg(nombre order by num) from public.kodesh_parashot where num = any (v_nums)),
    'total', cardinality(v_required),
    'read', (select count(*) from unnest(v_required) x where x = any (v_read)),
    'missing', (select coalesce(jsonb_agg(x order by x), '[]'::jsonb) from unnest(v_required) x where not (x = any (v_read))),
    'reward', 50 * cardinality(v_nums),
    'done', v_done
  );
end $$;

create or replace function public._kodesh_check_parasha(p_uid uuid)
returns void language plpgsql security definer set search_path = public as $$
declare
  v jsonb := public._kodesh_parasha_progress(p_uid);
begin
  if v is null or (v->>'done')::boolean or (v->>'read')::int < (v->>'total')::int then return; end if;
  perform public._kodesh_award(p_uid, (v->>'reward')::int, 'parasha', v->>'reading_day');
  perform public._kodesh_notice(p_uid, jsonb_build_object(
    'type', 'parasha', 'names', v->'names', 'mana', (v->>'reward')::int));
end $$;

-- record_chapter: el Shabat no corta la racha + revisa la parashá.
create or replace function public._kodesh_record_chapter(p_uid uuid, p_book text, p_chapter int)
returns void language plpgsql security definer set search_path = public as $$
declare
  v_today date := public._kodesh_today(p_uid);
  v_key text := upper(p_book) || ':' || p_chapter;
  v_day public.reading_days%rowtype;
  r public.reading_streaks%rowtype;
  v_n int;
  v_goal int;
  v_new_streak int;
  v_bonus int;
begin
  insert into public.reading_streaks (user_id) values (p_uid) on conflict (user_id) do nothing;
  perform public._kodesh_settle(p_uid);
  select * into r from public.reading_streaks where user_id = p_uid for update;

  insert into public.reading_days (user_id, day) values (p_uid, v_today) on conflict do nothing;
  select * into v_day from public.reading_days where user_id = p_uid and day = v_today for update;
  if v_key = any (v_day.chapters) then return; end if;

  v_n := cardinality(v_day.chapters) + 1;
  update public.reading_days
     set chapters = array_append(chapters, v_key),
         mana_earned = mana_earned + case when v_n <= 5 then 10 else 0 end,
         shielded = false
   where user_id = p_uid and day = v_today;
  if v_n <= 5 then perform public._kodesh_award(p_uid, 10, 'chapter', v_key); end if;

  select coalesce(reading_goal_chapters, 2) into v_goal from public.user_profiles where id = p_uid;
  v_goal := greatest(coalesce(v_goal, 2), 1);
  if v_n >= v_goal and not v_day.goal_bonus then
    update public.reading_days set goal_bonus = true, mana_earned = mana_earned + 20
     where user_id = p_uid and day = v_today;
    perform public._kodesh_award(p_uid, 20, 'goal', v_today::text);
  end if;

  if r.last_active_date is distinct from v_today then
    -- Continúa si entre el último día activo y hoy solo hubo sábados (o nada).
    v_new_streak := case
      when r.last_active_date is not null and r.current_streak > 0
           and public._kodesh_gap(r.last_active_date, v_today) = 0
      then r.current_streak + 1 else 1 end;
    update public.reading_streaks
       set current_streak = v_new_streak,
           longest_streak = greatest(longest_streak, v_new_streak),
           total_days_read = total_days_read + 1,
           last_read_date = v_today,
           last_active_date = v_today,
           updated_at = now()
     where user_id = p_uid;
    v_bonus := case v_new_streak when 7 then 50 when 30 then 200 when 100 then 500 when 365 then 1000 else 0 end;
    if v_bonus > 0 then
      perform public._kodesh_award(p_uid, v_bonus, 'milestone', v_new_streak::text);
      perform public._kodesh_notice(p_uid, jsonb_build_object('type', 'milestone', 'streak', v_new_streak, 'mana', v_bonus));
    end if;
  elsif r.last_read_date is distinct from v_today then
    update public.reading_streaks set last_read_date = v_today where user_id = p_uid;
  end if;

  perform public._kodesh_check_parasha(p_uid);
end $$;

-- ── 3. Créditos de IA ───────────────────────────────────────────────────
create or replace function public._kodesh_ai_limit(p_uid uuid, p_type text) returns int
language plpgsql stable security definer set search_path = public as $$
declare
  v_plan text; v_status text; v_end timestamptz; v_eff text := 'free';
begin
  select plan, subscription_status, current_period_end into v_plan, v_status, v_end
    from public.user_plans where user_id = p_uid;
  if v_status in ('active', 'trialing') and (v_end is null or v_end > now()) then
    v_eff := coalesce(v_plan, 'free');
  end if;
  return case
    when v_eff = 'premium' and p_type = 'search'    then 80
    when v_eff = 'premium' and p_type = 'assistant' then 70
    when v_eff = 'premium' and p_type = 'lexicon'   then 999999
    when p_type = 'search'    then 10
    when p_type = 'assistant' then 3
    else 15
  end;
end $$;

-- Igual que antes, pero al pasar el límite usa un crédito comprado con maná.
create or replace function public.consume_ai_usage(p_user_id uuid, p_type text)
returns jsonb language plpgsql security definer set search_path = public as $$
declare
  v_month text := to_char(now(), 'YYYY-MM');
  v_limit int;
  v_row public.ai_usage%rowtype;
  v_used int;
  v_credits int;
  v_plan text;
  v_status text;
  v_end timestamptz;
  v_eff text := 'free';
begin
  if p_type not in ('search', 'assistant', 'lexicon') then
    raise exception 'invalid_usage_type';
  end if;

  select plan, subscription_status, current_period_end into v_plan, v_status, v_end
    from public.user_plans where user_id = p_user_id;
  if v_status in ('active', 'trialing') and (v_end is null or v_end > now()) then
    v_eff := coalesce(v_plan, 'free');
  end if;
  v_limit := public._kodesh_ai_limit(p_user_id, p_type);

  insert into public.ai_usage (user_id, month) values (p_user_id, v_month)
    on conflict (user_id, month) do nothing;
  select * into v_row from public.ai_usage
   where user_id = p_user_id and month = v_month for update;

  v_used := case p_type when 'search' then v_row.searches_used
                        when 'assistant' then v_row.assistant_used
                        else v_row.lexicon_used end;

  if v_used >= v_limit then
    select case p_type when 'search' then credits_search
                       when 'assistant' then credits_assistant
                       else credits_lexicon end
      into v_credits
      from public.reading_streaks where user_id = p_user_id for update;
    if coalesce(v_credits, 0) <= 0 then
      return jsonb_build_object('allowed', false, 'used', v_used, 'limit', v_limit,
        'remaining', 0, 'plan', v_eff, 'month', v_month, 'credits', 0);
    end if;
    update public.reading_streaks set
      credits_search    = credits_search    - (p_type = 'search')::int,
      credits_assistant = credits_assistant - (p_type = 'assistant')::int,
      credits_lexicon   = credits_lexicon   - (p_type = 'lexicon')::int
     where user_id = p_user_id;
  end if;

  if p_type = 'search' then
    update public.ai_usage set searches_used = searches_used + 1, updated_at = now()
     where user_id = p_user_id and month = v_month;
  elsif p_type = 'assistant' then
    update public.ai_usage set assistant_used = assistant_used + 1, updated_at = now()
     where user_id = p_user_id and month = v_month;
  else
    update public.ai_usage set lexicon_used = lexicon_used + 1, updated_at = now()
     where user_id = p_user_id and month = v_month;
  end if;

  v_used := v_used + 1;
  return jsonb_build_object('allowed', true, 'used', v_used, 'limit', v_limit,
    'remaining', greatest(0, v_limit - v_used), 'plan', v_eff, 'month', v_month,
    'used_credit', v_used > v_limit);
end $$;

-- Si la IA falla, devolver la unidad; si esa unidad era un crédito, devolver el crédito.
create or replace function public.release_ai_usage(p_user_id uuid, p_type text)
returns void language plpgsql security definer set search_path = public as $$
declare
  v_month text := to_char(now(), 'YYYY-MM');
  v_used int;
begin
  select case p_type when 'search' then searches_used
                     when 'assistant' then assistant_used
                     when 'lexicon' then lexicon_used end
    into v_used
    from public.ai_usage where user_id = p_user_id and month = v_month for update;
  if v_used is null or v_used <= 0 then return; end if;

  if p_type = 'search' then
    update public.ai_usage set searches_used = searches_used - 1, updated_at = now()
     where user_id = p_user_id and month = v_month;
  elsif p_type = 'assistant' then
    update public.ai_usage set assistant_used = assistant_used - 1, updated_at = now()
     where user_id = p_user_id and month = v_month;
  elsif p_type = 'lexicon' then
    update public.ai_usage set lexicon_used = lexicon_used - 1, updated_at = now()
     where user_id = p_user_id and month = v_month;
  end if;

  if v_used > public._kodesh_ai_limit(p_user_id, p_type) then
    update public.reading_streaks set
      credits_search    = credits_search    + (p_type = 'search')::int,
      credits_assistant = credits_assistant + (p_type = 'assistant')::int,
      credits_lexicon   = credits_lexicon   + (p_type = 'lexicon')::int
     where user_id = p_user_id;
  end if;
end $$;

create or replace function public.buy_ai_credit(p_type text)
returns jsonb language plpgsql security definer set search_path = public as $$
declare
  v_uid uuid := auth.uid();
  r public.reading_streaks%rowtype;
  v_price int;
  v_have int;
begin
  if v_uid is null then raise exception 'not_authenticated'; end if;
  if p_type not in ('search', 'assistant', 'lexicon') then raise exception 'invalid_type'; end if;
  v_price := case p_type when 'assistant' then 50 when 'search' then 30 else 20 end;

  insert into public.reading_streaks (user_id) values (v_uid) on conflict (user_id) do nothing;
  select * into r from public.reading_streaks where user_id = v_uid for update;
  v_have := case p_type when 'search' then r.credits_search
                        when 'assistant' then r.credits_assistant
                        else r.credits_lexicon end;
  if v_have >= 10 then
    return jsonb_build_object('ok', false, 'error', 'max_credits', 'mana', r.mana, 'credits', v_have);
  end if;
  if r.mana < v_price then
    return jsonb_build_object('ok', false, 'error', 'insufficient_mana', 'mana', r.mana, 'price', v_price);
  end if;
  update public.reading_streaks set
    credits_search    = credits_search    + (p_type = 'search')::int,
    credits_assistant = credits_assistant + (p_type = 'assistant')::int,
    credits_lexicon   = credits_lexicon   + (p_type = 'lexicon')::int,
    updated_at = now()
   where user_id = v_uid;
  perform public._kodesh_award(v_uid, -v_price, 'ai_credit', p_type);
  return jsonb_build_object('ok', true, 'mana', r.mana - v_price, 'credits', v_have + 1, 'type', p_type);
end $$;

-- ── Estado para la app (añade parashá, créditos y si hoy es Shabat) ────
create or replace function public.get_my_streak_state(p_tz text default null)
returns jsonb language plpgsql security definer set search_path = public as $$
declare
  v_uid uuid := auth.uid();
  v_today date;
  v_month text;
  r public.reading_streaks%rowtype;
  v_premium boolean;
  v_today_n int;
  v_notices jsonb;
begin
  if v_uid is null then raise exception 'not_authenticated'; end if;

  if p_tz is not null and p_tz in (select name from pg_timezone_names) then
    update public.user_profiles set timezone = p_tz where id = v_uid and timezone is distinct from p_tz;
  end if;

  insert into public.reading_streaks (user_id) values (v_uid) on conflict (user_id) do nothing;
  perform public._kodesh_settle(v_uid);
  v_today := public._kodesh_today(v_uid);
  v_month := to_char(v_today, 'YYYY-MM');

  select * into r from public.reading_streaks where user_id = v_uid for update;

  select exists (
    select 1 from public.user_plans
     where user_id = v_uid and plan = 'premium'
       and subscription_status in ('active', 'trialing')
       and (current_period_end is null or current_period_end > public._kodesh_now())
  ) into v_premium;
  if v_premium and r.premium_shield_month is distinct from v_month and r.shields < 2 then
    update public.reading_streaks set shields = shields + 1, premium_shield_month = v_month where user_id = v_uid;
    perform public._kodesh_notice(v_uid, jsonb_build_object('type', 'premium_shield'));
  end if;

  select pending_notices into v_notices from public.reading_streaks where user_id = v_uid;
  update public.reading_streaks set pending_notices = '[]'::jsonb
   where user_id = v_uid
   returning * into r;
  select coalesce(cardinality(chapters), 0) into v_today_n
    from public.reading_days where user_id = v_uid and day = v_today;

  return jsonb_build_object(
    'current', r.current_streak,
    'longest', r.longest_streak,
    'total_days', r.total_days_read,
    'last_read_date', r.last_read_date,
    'last_active_date', r.last_active_date,
    'read_today', coalesce(r.last_read_date = v_today, false),
    'mana', r.mana,
    'shields', r.shields,
    'max_shields', 2,
    'shield_price', 200,
    'premium', v_premium,
    'today', v_today,
    'is_shabbat', extract(isodow from v_today) = 6,
    'today_chapters', coalesce(v_today_n, 0),
    'credits', jsonb_build_object('search', r.credits_search, 'assistant', r.credits_assistant, 'lexicon', r.credits_lexicon),
    'credit_prices', jsonb_build_object('search', 30, 'assistant', 50, 'lexicon', 20),
    'parasha', public._kodesh_parasha_progress(v_uid),
    'notices', v_notices
  );
end $$;

